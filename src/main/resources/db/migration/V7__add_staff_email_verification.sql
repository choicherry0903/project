ALTER TABLE staff_accounts ADD COLUMN email varchar(254) UNIQUE;

CREATE TABLE email_verification_tokens (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id bigint NOT NULL,
  staff_account_id bigint NOT NULL,
  token_hash varchar(64) NOT NULL UNIQUE,
  expires_at timestamp(6) with time zone NOT NULL,
  used_at timestamp(6) with time zone,
  created_at timestamp(6) with time zone NOT NULL,
  CONSTRAINT fk_email_verification_account
    FOREIGN KEY (company_id, staff_account_id) REFERENCES staff_accounts(company_id, id)
);

CREATE INDEX ix_email_verification_account
  ON email_verification_tokens(company_id, staff_account_id, expires_at);
