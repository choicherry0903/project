-- 조회와 고객 등록에서 사용하는 기존 테이블 컬럼만 재현한 테스트 전용 스키마.
-- 실제 Supabase DDL은 실행/변경하지 않는다.
CREATE SCHEMA IF NOT EXISTS interior_cms;
CREATE TABLE IF NOT EXISTS interior_cms.customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    request_key VARCHAR(36) NOT NULL DEFAULT RANDOM_UUID() UNIQUE,
    name VARCHAR(50) NOT NULL,
    phone VARCHAR(15) NOT NULL,
    archived BOOLEAN NOT NULL,
    UNIQUE (company_id, id)
);
CREATE TABLE IF NOT EXISTS interior_cms.construction_projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    customer_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    address VARCHAR(200) NOT NULL,
    detail_address VARCHAR(200),
    status VARCHAR(30) NOT NULL,
    construction_type VARCHAR(50) NOT NULL DEFAULT '미정',
    occupied BOOLEAN NOT NULL DEFAULT FALSE,
    on_hold BOOLEAN NOT NULL DEFAULT FALSE,
    request_key VARCHAR(36) NOT NULL DEFAULT RANDOM_UUID() UNIQUE,
    FOREIGN KEY (company_id, customer_id) REFERENCES interior_cms.customers(company_id, id)
);
CREATE TABLE IF NOT EXISTS interior_cms.staff_accounts (
    id BIGINT PRIMARY KEY,
    company_id BIGINT NOT NULL,
    username VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    display_name VARCHAR(50) NOT NULL,
    role VARCHAR(20) NOT NULL,
    active BOOLEAN NOT NULL,
    email VARCHAR(254),
    email_verified_at TIMESTAMP WITH TIME ZONE,
    UNIQUE (company_id, id)
);
CREATE TABLE IF NOT EXISTS interior_cms.consultations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    customer_id BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    content VARCHAR(2000) NOT NULL,
    FOREIGN KEY (company_id, customer_id) REFERENCES interior_cms.customers(company_id, id),
    FOREIGN KEY (company_id, author_id) REFERENCES interior_cms.staff_accounts(company_id, id)
);
-- 고객별 상담 항목을 구조화해서 저장한다. 기존 상담 데이터는 변경하지 않는다.
CREATE TABLE IF NOT EXISTS interior_cms.customer_consultation_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    customer_id BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    sort_order INTEGER NOT NULL CHECK (sort_order >= 0),
    category VARCHAR(100) NOT NULL,
    custom_category VARCHAR(100),
    content VARCHAR(2000) NOT NULL,
    CONSTRAINT uq_customer_consultation_order UNIQUE (company_id, customer_id, sort_order),
    CONSTRAINT fk_customer_consultation_customer FOREIGN KEY (company_id, customer_id)
        REFERENCES interior_cms.customers(company_id, id),
    CONSTRAINT fk_customer_consultation_author FOREIGN KEY (company_id, author_id)
        REFERENCES interior_cms.staff_accounts(company_id, id),
    CONSTRAINT ck_customer_consultation_content CHECK (LENGTH(TRIM(content)) > 0),
    CONSTRAINT ck_customer_consultation_category CHECK (LENGTH(TRIM(category)) > 0),
    CONSTRAINT ck_customer_consultation_custom CHECK
        (category <> '기타' OR (custom_category IS NOT NULL AND LENGTH(TRIM(custom_category)) > 0))
);
