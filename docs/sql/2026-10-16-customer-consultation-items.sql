-- 고객별 상담 항목을 구조화해서 저장한다. 기존 상담 데이터는 변경하지 않는다.
CREATE TABLE IF NOT EXISTS interior_cms.customer_consultation_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    customer_id BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    sort_order INTEGER NOT NULL CHECK (sort_order >= 0),
    category VARCHAR(100) NOT NULL,
    custom_category VARCHAR(100),
    content VARCHAR(2000) NOT NULL,
    CONSTRAINT uq_customer_consultation_order UNIQUE (company_id, customer_id, sort_order),
    CONSTRAINT fk_customer_consultation_customer FOREIGN KEY (company_id, customer_id)
        REFERENCES interior_cms.customers(company_id, id),
    CONSTRAINT fk_customer_consultation_author FOREIGN KEY (company_id, author_id)
        REFERENCES interior_cms.staff_accounts(company_id, id),
    CONSTRAINT ck_customer_consultation_content CHECK (LENGTH(TRIM(content)) > 0),
    CONSTRAINT ck_customer_consultation_category CHECK (LENGTH(TRIM(category)) > 0),
    CONSTRAINT ck_customer_consultation_custom CHECK
        (category <> '기타' OR (custom_category IS NOT NULL AND LENGTH(TRIM(custom_category)) > 0))
);
